BEGIN;
SET LOCAL search_path TO public;

-- Tabela de Usuários
CREATE TABLE IF NOT EXISTS usuarios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    email VARCHAR(100) UNIQUE NOT NULL,
    senha VARCHAR(255) NOT NULL,
    criado_em TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);
-- Tabela de Cartões
CREATE TABLE IF NOT EXISTS cartoes (

    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INT NOT NULL,
    nome VARCHAR(100) NOT NULL,
    banco VARCHAR(100) NOT NULL,
    limite DECIMAL(10,2) NOT NULL,
    dia_fechamento INT NOT NULL,
    dia_vencimento INT NOT NULL,
    final_cartao VARCHAR(4) NOT NULL,
    cor VARCHAR(30) DEFAULT 'roxo',
    criado_em TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE

);

-- Tabela de Movimentações
CREATE TABLE IF NOT EXISTS movimentacoes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INT NOT NULL,
    tipo VARCHAR(7) NOT NULL CHECK (tipo IN ('receita', 'despesa')),
    descricao VARCHAR(200) NOT NULL,
    valor DECIMAL(15,2) NOT NULL,
    categoria VARCHAR(100),
    forma_pagamento VARCHAR(50),
    data DATE NOT NULL,
    criado_em TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE
);

-- Tabela de Categorias
CREATE TABLE IF NOT EXISTS categorias (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    tipo VARCHAR(7) NOT NULL CHECK (tipo IN ('receita', 'despesa')),
    CONSTRAINT uk_categoria UNIQUE (nome, tipo)
);

-- Categorias iniciais
INSERT INTO categorias (nome, tipo) VALUES
('Salário', 'receita'), ('Freelance', 'receita'),
('Alimentação', 'despesa'), ('Transporte', 'despesa'),
('Moradia', 'despesa'), ('Lazer', 'despesa'),
('Saúde', 'despesa'), ('Educação', 'despesa'),
('Vestuário', 'despesa'), ('Outros', 'despesa')
ON CONFLICT (nome, tipo) DO NOTHING;

-- Índices das chaves estrangeiras para consultas por usuário.
CREATE INDEX IF NOT EXISTS idx_cartoes_usuario ON cartoes (usuario_id);
CREATE INDEX IF NOT EXISTS idx_movimentacoes_usuario_data ON movimentacoes (usuario_id, data DESC);

-- Acesso somente pelo backend. Sem políticas públicas de acesso pelo Data API.
-- O usuário postgres do Session Pooler possui BYPASSRLS; o filtro usuario_id
-- continua obrigatório nos models. Uma role restrita exigiria políticas próprias.
ALTER TABLE usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE cartoes ENABLE ROW LEVEL SECURITY;
ALTER TABLE movimentacoes ENABLE ROW LEVEL SECURITY;
ALTER TABLE categorias ENABLE ROW LEVEL SECURITY;

COMMIT;
